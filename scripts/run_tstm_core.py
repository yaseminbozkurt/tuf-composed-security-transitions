# P4 -- metadata signed only by a since-removed root key must be REJECTED
# ---------------------------------------------------------------------
def p4_case(repo, client, init_data):
    """P4: after a GENUINELY VALID root rotation (dual-signed by both the
    old-trusted threshold AND the new threshold, per spec Sec.5.3.4), a
    later root version signed ONLY by the now-removed old key must be
    rejected."""
    assert client.init_client(init_data) == 0
    r0 = client.refresh(init_data)  # SETUP: trust root v1

    old_signers = dict(repo.signers[Root.type])  # capture BEFORE rotation

    # Genuinely valid rotation: sign v2 with BOTH old signer(s) AND new
    # signer(s), satisfying the dual-threshold requirement, matching the
    # pattern proven in tuf-conformance's own test_root_rotation.
    new_signer = repo.new_signer()
    repo.root.add_key(new_signer.public_key, Root.type)
    repo.root.roles[Root.type].keyids.clear()
    repo.root.add_key(new_signer.public_key, Root.type)  # new key is now sole authorized key for v2
    repo.signers[Root.type] = {new_signer.public_key.keyid: new_signer}
    manual_publish_with_signers(
        repo, Root.type, list(old_signers.values()) + [new_signer]
    )  # v2 signed by BOTH v1-threshold key(s) AND v2-threshold key -> genuinely valid
    r1 = client.refresh(init_data)  # decision for ROOT_ROTATE_VALID

    # Now attempt root v3 signed ONLY by the OLD (v1, now-removed) key
    manual_publish_with_signers(repo, Root.type, list(old_signers.values()))
    r2 = client.refresh(init_data)  # decision for METADATA_BY_REMOVED_KEY
    return {
        "baseline_refresh_v1": r0,
        "refresh_after_genuinely_valid_rotation_v2": r1,
        "refresh_v3_signed_only_by_removed_v1_key": r2,
    }


run_case(
    "F5", "P4", ["P4"], ["ROOT_ROTATE_VALID", "METADATA_BY_REMOVED_KEY"],
    step_role_map={
        "baseline_refresh_v1": "SETUP",
        "refresh_after_genuinely_valid_rotation_v2": "ROOT_ROTATE_VALID",
        "refresh_v3_signed_only_by_removed_v1_key": "METADATA_BY_REMOVED_KEY",
    },
    boundary_states=["KEY_REMOVED", "KEY_FULL_REPLACEMENT"],
    fn=p4_case,
)


