# P5 -- stale delegated metadata must be REJECTED after delegation removal
# ---------------------------------------------------------------------
def p5_case(repo, client, init_data):
    assert client.init_client(init_data) == 0
    role = DelegatedRole("delegated", [], 1, False, ["delegatedpath/*"])
    delegated_targets = Targets(expires=repo.safe_expiry)
    repo.add_delegation(Targets.type, role, delegated_targets)
    repo.add_artifact("delegated", b"real-target-content-for-p5-test", "delegatedpath/foo")
    repo.publish(["delegated", Targets.type])
    repo.publish([Snapshot.type, Timestamp.type])  # required: makes "delegated.json" actually visible to client
    r0 = client.refresh(init_data)  # decision for DELEGATION_CREATE (first time it's visible to the client)
    r0b = client.download_target(init_data, "delegatedpath/foo")  # SETUP: confirms the delegation actually works

    # Remove the delegation entirely (not just from snapshot -- full authorization removal)
    del repo.targets.delegations.roles["delegated"]
    repo.publish([Targets.type, Snapshot.type, Timestamp.type])
    r1 = client.refresh(init_data)  # decision for DELEGATION_REMOVE
    r2 = client.download_target(init_data, "delegatedpath/foo")  # decision for DELEGATED_REPLAY_AFTER_REMOVAL
    final_version = client.version("delegated")  # INTROSPECTION only -- a version number, NOT a decision
    return {
        "refresh_with_delegation": r0,
        "download_via_delegation": r0b,
        "refresh_after_delegation_removed": r1,
        "download_after_delegation_removed": r2,
        "final_delegated_role_version": final_version,
    }


run_case(
    "F4", "P5", ["P5"],
    ["DELEGATION_CREATE", "DELEGATION_REMOVE", "DELEGATED_REPLAY_AFTER_REMOVAL"],
    step_role_map={
        "refresh_with_delegation": "DELEGATION_CREATE",
        "download_via_delegation": "SETUP",
        "refresh_after_delegation_removed": "DELEGATION_REMOVE",
        "download_after_delegation_removed": "DELEGATED_REPLAY_AFTER_REMOVAL",
        "final_delegated_role_version": "INTROSPECTION",
    },
    boundary_states=["DELEGATION_ACTIVE", "DELEGATION_REMOVED"],
    fn=p5_case,
)


