# Real, freshly-initialized RepositorySimulator state -- identical for every
# case below, since every case calls server.new_test() (a fresh simulator)
# before doing anything else. Not a placeholder: this is what
# SimulatorServer.new_test() actually constructs (root v1, single key,
# threshold 1, timestamp/snapshot/targets v1, no delegations, valid
# expiration), per direct reading of
# tuf_conformance/_internal/simulator_server.py and repository_simulator.py
# in this pinned checkout (see ../REPRODUCIBILITY.md for the commit hash).
FRESH_INITIAL_STATE = {
    "R_v": 1, "R_K": ["root_key_0"], "R_t": 1,
    "T_v": 1, "S_v": 1, "G_v": 1,
    "D": "DELEGATION_ABSENT", "E": "EXPIRATION_VALID",
}


def manual_publish_with_signers(repo, role: str, signers: list, replace_current: bool = False) -> None:
    """Replicates RepositorySimulator.publish()'s core signing logic but with
    an explicit signer list instead of repo.signers[role]. Used to construct
    root versions signed by an explicit, controlled key set.

    replace_current=True republishes the SAME version number (does not
    increment) and REPLACES the last entry in repo.signed_mds[role] in place,
    instead of appending a new one. This is required to correctly model
    "the repo owner fixes and republishes version N" (e.g. a recovery after a
    bad signing attempt) -- TUF's root-update loop fetches root versions
    strictly sequentially via repo.signed_mds[role][version - 1] (see
    repository_simulator.py), so appending a NEW list entry instead of
    replacing would serve it as a *different, later* version, which a client
    still stuck failing to verify the earlier bad version could never reach.
    Discovered as a genuine construction bug in an early attempt at the P1
    reject->recovery sequence: appending instead of replacing made both
    clients correctly REJECT the "recovery" step, not because recovery
    itself is unsupported, but because the bad intermediate version was
    still blocking the sequential root-update chain. See
    tuf_study/baseline/ for the full writeup."""
    from tuf.api.serialization.json import JSONSerializer

    md = repo.mds[role]
    if not replace_current:
        md.signed.version += 1
    md.signatures.clear()
    for signer in signers:
        md.sign(signer, append=True)
    if role not in repo.signed_mds:
        repo.signed_mds[role] = []
    encoded = md.to_bytes(JSONSerializer())
    if replace_current and repo.signed_mds[role]:
        repo.signed_mds[role][-1] = encoded
    else:
        repo.signed_mds[role].append(encoded)
    if role not in [Root.type, Timestamp.type, Snapshot.type]:
        repo.snapshot.meta[f"{role}.json"] = MetaFile(md.signed.version, None, None)
    if role == Snapshot.type:
        repo.timestamp.snapshot_meta = MetaFile(md.signed.version, None, None)


results = []
