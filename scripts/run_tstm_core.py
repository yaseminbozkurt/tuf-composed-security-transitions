def run_case(family: str, case_label: str, oracle_properties: list[str],
             transitions_desc: list[str], step_role_map: dict[str, str],
             boundary_states: list[str], fn, control_case_note: str | None = None):
    """fn(repo, client, init_data) -> dict of {step_name: exit_code / value}.
    Executed once per implementation.

    case_label: internal unique identifier (e.g. "P1", "P1_CONTROL") used for
      test naming and for keying build_real_dataset.py's per-case tables.
      Always non-empty, always used for sequence_id hashing (so demoting a
      case to a control does not silently collide its ID with anything).
    oracle_properties: the OFFICIAL, schema-constrained list this sequence
      counts toward (subset of P1-P5). Empty for a control/overlap case that
      should not contribute to this study's coverage claims.
    step_role_map: maps every key `fn` can return to one of:
      - a transition_type string in `transitions_desc` (this step IS the
        observed decision for that modeled transition),
      - "SETUP" (a real client call, not itself a modeled transition),
      - "INTROSPECTION" (not a decision at all -- e.g. a version number;
        must never appear in a decision trace).
    """
    cid = pl.sequence_id(family, [case_label], transitions_desc)
    entry = {
        "sequence_id": cid, "family": family, "case_label": case_label, "origin": "TSTM_GENERATED",
        "transitions": [{"step_index": i, "transition_type": t, "parameters": {}, "counts_toward_k": True}
                         for i, t in enumerate(transitions_desc)],
        "length": len(transitions_desc), "oracle_properties": oracle_properties,
        "initial_state": FRESH_INITIAL_STATE,
        "step_role_map": step_role_map,
        "boundary_states": boundary_states,
    }
    if control_case_note:
        entry["control_case_note"] = control_case_note
    corpus.append(entry)
    for impl_name, entry_path in IMPLS.items():
        test_name = f"{family}_{case_label}_{impl_name}".replace(" ", "_")
        client = ClientRunner(entry_path, server, test_name)
        init_data, repo = server.new_test(test_name)
        try:
            step_results = fn(repo, client, init_data)
        except Exception as e:
            step_results = {"EXCEPTION": str(e)}
        results.append({
            "sequence_id": cid, "implementation": impl_name,
            "family": family, "case_label": case_label,
            "step_results": step_results,
        })
        print(f"[{family}/{case_label}] {impl_name}: {step_results}")


