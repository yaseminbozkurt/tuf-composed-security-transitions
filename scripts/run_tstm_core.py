# P2 -- skipped root version must be REJECTED (root_v1 -> root_v3, no v2)
# ---------------------------------------------------------------------
def p2_case(repo, client, init_data):
    assert client.init_client(init_data) == 0
    r0 = client.refresh(init_data)  # SETUP: initial trust-bootstrap refresh at v1
    # Force a version SKIP: bump root version by 2 in one publish (v1->v3).
    # There is no intermediate valid v1->v2 rotation in this case at all.
    repo.root.version += 1
    repo.rotate_keys(Root.type)
    repo.publish([Root.type], verify_version=False)  # v1 -> v3 directly
    r1 = client.refresh(init_data)  # decision for ROOT_ROTATE_SKIP
    return {"baseline_refresh": r0, "refresh_after_skip_v1_to_v3": r1}


run_case(
    "F1", "P2", ["P2"], ["ROOT_ROTATE_SKIP"],
    step_role_map={"baseline_refresh": "SETUP", "refresh_after_skip_v1_to_v3": "ROOT_ROTATE_SKIP"},
    boundary_states=["VERSION_SKIPPED_NEXT"],
    fn=p2_case,
)


