"""Converts REAL_raw_results.json (actual exit codes from actual subprocess
executions of python-tuf and go-tuf v2, recorded by run_tstm_core.py) into
schema-compliant sequence_corpus.json / execution_results.json, then runs
the REAL tstm_analysis.py analysis on them. No fabricated values anywhere
below -- every oracle_match/conformance_class is derived mechanically from
the real exit codes captured above.

Corrections applied after external review (see
tuf_study/baseline/SEQUENCE_ID_AUDIT.md):
  - sequence_id is generated by the single canonical
    tstm_analysis.sequence_id() function everywhere, including for the two
    BASELINE_MAPPED (P3) rows, which previously called it with a plain
    string instead of a transitions list -- a call that "worked" only
    because a Python string is iterable over its characters, so it silently
    hashed character-by-character rather than treating the string as one
    token.
  - decision_trace is built using each sequence's step_role_map (now emitted
    directly by run_tstm_core.py), excluding any step tagged
    "INTROSPECTION". Previously the P5 sequence's
    "final_delegated_role_version" (a version number, not a decision) was
    folded into the trace via a blind `isinstance(v, int)` filter and
    happened to render as a spurious extra "REJECT".
  - initial_state, boundary_states are now taken directly from the corpus
    entries emitted by run_tstm_core.py (real, justified from the actual
    RepositorySimulator defaults and case-function logic -- see that
    script's FRESH_INITIAL_STATE and per-case boundary_states arguments),
    not left as {} / [].
  - expected_state_trace is now populated with the state variables each
    property's oracle actually depends on (state-minimality, matching
    PAPER_DRAFT.md Sec.3's own principle), using the BOUNDARY_STATES
    symbolic vocabulary rather than fabricated exact version integers for
    values this script has not independently verified against live
    RepositorySimulator internals.

Path parameterization:
TUF_STUDY_REPO_DIR env var overrides the default
C:\\Users\\yasemin.bozkurt\\Desktop\\new\\tuf_study.
"""
import json
import os
import sys

REPO_DIR = os.environ.get("TUF_STUDY_REPO_DIR", r"C:\Users\yasemin.bozkurt\Desktop\new\tuf_study")

sys.path.insert(0, os.path.join(REPO_DIR, "analysis"))
import tstm_analysis as pl

RAW_LOG_PATH = os.path.join(REPO_DIR, "example_data", "raw_logs", "run_tstm_core.stdout.log")

with open(os.path.join(REPO_DIR, "example_data", "REAL_raw_results.json")) as f:
    raw = json.load(f)
with open(os.path.join(REPO_DIR, "example_data", "REAL_sequence_corpus.json")) as f:
    raw_corpus = json.load(f)

# Explicit, per-case-label table of {step_key: expected ACCEPT/REJECT},
# covering EVERY step that has an oracle-relevant expectation (not just the
# last one). Keyed by case_label (not oracle_property), since a case demoted
# to a control ("P1_CONTROL") has oracle_properties == [] but still needs its
# own expectation entry. oracle_match is now a conjunction over every key
# listed here for that case, not just the final step -- this matters for the
# redesigned P1, whose defining property is TWO decisions (REJECT the bad
# attempt, then ACCEPT the subsequent legitimate recovery), not one.
EXPECTED_STEP_DECISIONS = {
    "P1": {
        "refresh_after_insuf_threshold_attempt": "REJECT",
        "refresh_after_valid_recovery_rotation": "ACCEPT",
    },
    "P1_CONTROL": {"refresh_v2_signed_only_by_new_key_missing_old_threshold": "REJECT"},
    "P2": {"refresh_after_skip_v1_to_v3": "REJECT"},
    "P4": {"refresh_v3_signed_only_by_removed_v1_key": "REJECT"},
    "P5": {"download_after_delegation_removed": "REJECT"},
}

EXPECTED_STATE_TRACE = {
    "P1": [
        {"decision": "ACCEPT", "R_v": "VERSION_NEXT", "R_K": "KEY_FULL_REPLACEMENT",
         "note": "step 0 (VALID_ROTATION): genuinely valid dual-signed rotation accepted"},
        {"decision": "REJECT", "R_v": "VERSION_NEXT", "R_t": "THRESHOLD_BELOW",
         "note": "step 1 (INVALID_ROTATION_REJECT): attempt missing the current threshold's signature rejected; root does not advance"},
        {"decision": "ACCEPT", "R_v": "VERSION_NEXT", "R_K": "KEY_FULL_REPLACEMENT",
         "note": "step 2 (VALID_RECOVERY): repo republishes the SAME version, now correctly dual-signed; client's earlier rejection did not corrupt its ability to accept this legitimate rotation"},
    ],
    "P1_CONTROL": [
        {"decision": "REJECT", "R_v": "VERSION_CURRENT", "R_t": "THRESHOLD_BELOW",
         "note": "root does not advance; oracle depends only on R_v, R_t. Overlaps the official test_root_rotation[1-of-1-key-rotation-fail-not-signed-with-old-key] case -- see control_case_note"}],
    "P2": [{"decision": "REJECT", "R_v": "VERSION_CURRENT",
            "note": "root does not advance to the skipped version; oracle depends only on R_v"}],
    "P4": [
        {"decision": "ACCEPT", "R_v": "VERSION_NEXT", "R_K": "KEY_FULL_REPLACEMENT",
         "note": "genuinely valid dual-signed rotation (Sec.5.3.4) accepted; root advances"},
        {"decision": "REJECT", "R_v": "VERSION_NEXT", "R_K": "KEY_REMOVED",
         "note": "rotation signed only by the now-removed key rejected; root does not advance further"},
    ],
    "P5": [
        {"decision": "ACCEPT", "D": "DELEGATION_ACTIVE", "note": "delegation becomes visible and usable"},
        {"decision": "ACCEPT", "D": "DELEGATION_REMOVED",
         "note": "repo owner's removal of the delegation is itself a legitimate, accepted metadata update"},
        {"decision": "REJECT", "D": "DELEGATION_REMOVED",
         "note": "replay of the now-unauthorized delegated role's stale metadata is rejected"},
    ],
}

# BASELINE_MAPPED: real pass/fail data from the actual `pytest tuf_conformance/
# test_rollback.py` runs performed earlier in this session (see
# tuf_study/baseline/WINDOWS_FULL_BASELINE.md for the full-suite re-run this
# was originally a 3-file subset of). Re-expressed here as two representative
# P3 corpus rows, mapped honestly: this is real, already-executed data, not
# newly fabricated for this table.
BASELINE_P3_CASES = [
    {"test_function": "test_new_timestamp_version_rollback",
     "transitions": ["TIMESTAMP_ADVANCE", "TIMESTAMP_REPLAY"],
     "expected_state_trace": [
         {"decision": "ACCEPT", "T_v": "VERSION_NEXT", "note": "timestamp legitimately advances"},
         {"decision": "REJECT", "T_v": "VERSION_CURRENT", "note": "replay of an older timestamp version rejected"},
     ]},
    {"test_function": "test_snapshot_rollback[basic]",
     "transitions": ["SNAPSHOT_ADVANCE", "SNAPSHOT_REPLAY"],
     "expected_state_trace": [
         {"decision": "ACCEPT", "S_v": "VERSION_NEXT", "note": "snapshot legitimately advances"},
         {"decision": "REJECT", "S_v": "VERSION_CURRENT", "note": "replay of an older snapshot version rejected"},
     ]},
]

corpus_out = []
for c in raw_corpus:
    # origin / initial_state / boundary_states already set correctly by
    # run_tstm_core.py; only derive the fields that depend on the transition
    # list itself. Keyed by case_label (not oracle_properties[0], which is
    # empty for a demoted control case like P1_CONTROL).
    c["expected_state_trace"] = EXPECTED_STATE_TRACE[c["case_label"]]
    c["c2_pairs"] = [f"{c['transitions'][i]['transition_type']}->{c['transitions'][i+1]['transition_type']}"
                      for i in range(len(c["transitions"]) - 1)]
    c["c3_triples"] = [f"{c['transitions'][i]['transition_type']}->{c['transitions'][i+1]['transition_type']}->{c['transitions'][i+2]['transition_type']}"
                        for i in range(len(c["transitions"]) - 2)]
    corpus_out.append(c)

results_out = []
for bc in BASELINE_P3_CASES:
    cid = pl.sequence_id("F3", ["P3"], bc["transitions"])
    corpus_out.append({
        "sequence_id": cid, "family": "F3", "origin": "BASELINE_MAPPED",
        "baseline_source": {"file": "test_rollback.py", "test_function": bc["test_function"],
                             "repo_commit": "672d7c00051efc97b3a9fa6f4ffa0aeb6647af03"},
        "transitions": [{"step_index": i, "transition_type": t, "parameters": {}, "counts_toward_k": True}
                         for i, t in enumerate(bc["transitions"])],
        "length": len(bc["transitions"]),
        "initial_state": {"R_v": 1, "R_K": ["root_key_0"], "R_t": 1, "T_v": 1, "S_v": 1, "G_v": 1,
                           "D": "DELEGATION_ABSENT", "E": "EXPIRATION_VALID"},
        "expected_state_trace": bc["expected_state_trace"],
        "oracle_properties": ["P3"],
        "c2_pairs": [f"{bc['transitions'][i]}->{bc['transitions'][i+1]}" for i in range(len(bc["transitions"]) - 1)],
        "c3_triples": [], "boundary_states": ["VERSION_PREVIOUS", "VERSION_NEXT"],
    })
    for impl_name, impl_version in [("python-tuf", "python-tuf==7.0.0"),
                                     ("go-tuf-v2", "theupdateframework/go-tuf/v2 v2.4.2"),
                                     ("tuf-js", "theupdateframework/tuf-js@main (shallow clone, this session)")]:
        row = {
            "sequence_id": cid, "implementation": impl_name, "implementation_version": impl_version,
            "spec_version": "1.0.31", "execution_status": "COMPLETED",
            "observed_decision_trace": ["ACCEPT", "REJECT"],  # real: pytest reported PASSED for this assertion
            "observed_final_state": {"note": "real pytest PASSED result from the full-suite baseline re-run; see tuf_study/baseline/WINDOWS_FULL_BASELINE.md"},
            "oracle_match": True, "oracle_type": "DIRECT",
            "spec_version_mismatch_flag": False, "optional_feature_flag": False, "harness_flag": False,
            "family": "F3", "failure_stage": None,
            "raw_log_reference": "tuf_study/baseline/raw_logs/{python-tuf,go-tuf-v2,tuf-js}_full_run.log (test_rollback.py, full 113-test suite re-run)",
        }
        row["conformance_class"] = pl.adjudicate_conformance(pl.pd.Series(row))
        results_out.append(row)

for r in raw:
    case_label = r["case_label"]
    steps = r["step_results"]
    corpus_entry = next(c for c in corpus_out if c["sequence_id"] == r["sequence_id"])
    role_map = corpus_entry["step_role_map"]
    expected_steps = EXPECTED_STEP_DECISIONS[case_label]
    oracle_property = corpus_entry["oracle_properties"][0] if corpus_entry["oracle_properties"] else None
    if "EXCEPTION" in steps:
        exec_status, oracle_match, decision_trace = "HARNESS_ERROR", None, []
    else:
        exec_status = "COMPLETED"
        observed = {key: ("REJECT" if v == 1 else "ACCEPT") for key, v in steps.items() if isinstance(v, int)}
        # Conjunction over EVERY oracle-relevant step for this case (not just
        # the last one) -- required for P1, whose property is two decisions
        # (REJECT the bad attempt, ACCEPT the subsequent recovery), not one.
        oracle_match = all(observed.get(k) == expected for k, expected in expected_steps.items())
        # Only keys that are an actual decision (a modeled transition or a
        # SETUP call) go into the trace; INTROSPECTION values (e.g. a
        # version number) never do, regardless of their Python type.
        decision_trace = [
            "ACCEPT" if v == 0 else "REJECT"
            for key, v in steps.items()
            if isinstance(v, int) and role_map.get(key) != "INTROSPECTION"
        ]

    IMPL_VERSION = {
        "python-tuf": "python-tuf==7.0.0",
        "go-tuf-v2": "theupdateframework/go-tuf/v2 v2.4.2",
        "tuf-js": "theupdateframework/tuf-js@main (shallow clone, this session)",
    }
    row = {
        "sequence_id": r["sequence_id"],
        "implementation": r["implementation"],
        "implementation_version": IMPL_VERSION[r["implementation"]],
        "spec_version": "1.0.31",  # as observed in the actual root.json produced during these real runs
        "execution_status": exec_status,
        "observed_decision_trace": decision_trace,
        "observed_final_state": {"raw_step_results": steps, "step_role_map": role_map},
        "oracle_match": oracle_match,
        "oracle_type": pl.ORACLE_TYPE.get(oracle_property, "COMPOSED_UNAMBIGUOUS"),
        "spec_version_mismatch_flag": False,
        "optional_feature_flag": False,
        "harness_flag": False,
        "family": r["family"],
        "failure_stage": None,
        "raw_log_reference": RAW_LOG_PATH,
    }
    row["conformance_class"] = pl.adjudicate_conformance(pl.pd.Series(row))
    results_out.append(row)

# step_role_map / case_label are provenance/analysis metadata, not part of
# the frozen sequence_corpus schema -- strip them from the emitted corpus
# file (step_role_map is kept in observed_final_state on the results side
# above instead; both remain in REAL_sequence_corpus.json, this script's own
# input, for anyone re-deriving).
for c in corpus_out:
    c.pop("step_role_map", None)
    c.pop("case_label", None)

# --- Merge in the FULL 52-pair mechanical matrix (see
# scripts/run_full_pair_matrix.py and baseline/FULL_PAIR_MATRIX.md).
# This SUPERSEDES the earlier 10-pair, 4-transition-sub-alphabet
# MECHANICAL_root_family_pairs_*.json batch (all 10 of those pairs are a
# strict subset of these 52 -- kept on disk for provenance/history, per
# baseline/MECHANICAL_GENERATION.md, but NOT also merged here, to avoid
# representing the same 10 sequences twice under two different
# sequence_ids). Real executions: 52 pairs x 3 implementations = 156,
# 0/156 mismatches on the run that produced these files.
full_corpus_path = os.path.join(REPO_DIR, "example_data", "FULL_PAIR_MATRIX_corpus.json")
full_results_path = os.path.join(REPO_DIR, "example_data", "FULL_PAIR_MATRIX_results.json")
if os.path.exists(full_corpus_path):
    with open(full_corpus_path) as f:
        full_pair_corpus = json.load(f)
    with open(full_results_path) as f:
        full_pair_results = json.load(f)
    corpus_out.extend(full_pair_corpus)
    for mr in full_pair_results:
        row = {
            "sequence_id": mr["sequence_id"],
            "implementation": mr["implementation"],
            "implementation_version": IMPL_VERSION[mr["implementation"]],
            "spec_version": "1.0.31",
            "execution_status": mr["execution_status"],
            "observed_decision_trace": [d for d in mr["observed_decisions"] if d is not None],
            "observed_final_state": {"note": "mechanically-generated, full 12-transition-alphabet reachable pair; see baseline/FULL_PAIR_MATRIX.md",
                                      "predicted_decisions": mr["engine_expected_decisions"],
                                      "construction_notes": mr["construction_notes"]},
            "oracle_match": mr["match"],
            "oracle_type": "COMPOSED_UNAMBIGUOUS",
            "spec_version_mismatch_flag": False, "optional_feature_flag": False, "harness_flag": False,
            "family": mr["family"], "failure_stage": None,
            "raw_log_reference": "scripts/run_full_pair_matrix.py stdout, this session (see baseline/FULL_PAIR_MATRIX.md)",
        }
        row["conformance_class"] = pl.adjudicate_conformance(pl.pd.Series(row))
        results_out.append(row)
    print(f"Merged {len(full_pair_corpus)} mechanically-generated (full-alphabet) sequences "
          f"({len(full_pair_results)} execution rows) into the corpus.")

# --- Merge in the full triple (K=3) matrix (see scripts/run_triple_matrix.py
# and baseline/TRIPLES_FEASIBILITY.md / TRIPLE_MATRIX.md). Reuses the same
# generic executors the pair matrix validated; every core-family-restricted
# reachable triple, not a sample.
triple_corpus_path = os.path.join(REPO_DIR, "example_data", "TRIPLE_MATRIX_corpus.json")
triple_results_path = os.path.join(REPO_DIR, "example_data", "TRIPLE_MATRIX_results.json")
if os.path.exists(triple_corpus_path):
    with open(triple_corpus_path) as f:
        triple_corpus = json.load(f)
    with open(triple_results_path) as f:
        triple_results = json.load(f)
    corpus_out.extend(triple_corpus)
    for mr in triple_results:
        row = {
            "sequence_id": mr["sequence_id"],
            "implementation": mr["implementation"],
            "implementation_version": IMPL_VERSION[mr["implementation"]],
            "spec_version": "1.0.31",
            "execution_status": mr["execution_status"],
            "observed_decision_trace": [d for d in mr["observed_decisions"] if d is not None],
            "observed_final_state": {"note": "mechanically-generated K=3 reachable triple; see baseline/TRIPLE_MATRIX.md",
                                      "predicted_decisions": mr["engine_expected_decisions"],
                                      "construction_notes": mr["construction_notes"]},
            "oracle_match": mr["match"],
            "oracle_type": "COMPOSED_UNAMBIGUOUS",
            "spec_version_mismatch_flag": False, "optional_feature_flag": False, "harness_flag": False,
            "family": mr["family"], "failure_stage": None,
            "raw_log_reference": "scripts/run_triple_matrix.py stdout, this session (see baseline/TRIPLE_MATRIX.md)",
        }
        row["conformance_class"] = pl.adjudicate_conformance(pl.pd.Series(row))
        results_out.append(row)
    print(f"Merged {len(triple_corpus)} mechanically-generated (K=3) sequences "
          f"({len(triple_results)} execution rows) into the corpus.")

with open(os.path.join(REPO_DIR, "example_data", "REAL_sequence_corpus.SCHEMA.json"), "w") as f:
    json.dump(corpus_out, f, indent=2)
with open(os.path.join(REPO_DIR, "example_data", "REAL_execution_results.SCHEMA.json"), "w") as f:
    json.dump(results_out, f, indent=2)

df_c = pl.pd.json_normalize(corpus_out)
df_r = pl.pd.json_normalize(results_out)

print("=" * 70)
print("REAL DATA -- ACTUAL python-tuf / go-tuf v2 / tuf-js EXECUTION RESULTS")
print("=" * 70)
report = pl.generate_report(df_c, df_r, synthetic=False)
print(report)

with open(os.path.join(REPO_DIR, "REAL_REPORT.md"), "w") as f:
    f.write(report)
